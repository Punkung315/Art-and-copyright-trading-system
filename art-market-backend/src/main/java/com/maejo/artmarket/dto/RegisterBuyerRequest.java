package com.maejo.artmarket.dto;

import jakarta.validation.Valid;
import jakarta.validation.constraints.*;
import lombok.Data;

/**
 * DTO รับข้อมูลสมัครสมาชิกผู้ซื้อ (ยูสเคส 3.1.3 Register Buyer หน้า 23-24)
 * Validation rules ตรงตาม "ความต้องการของระบบ" ที่ SRS กำหนดทุกข้อ
 *
 * ตั้งแต่รอบแก้นี้ ผู้ซื้อต้องกรอกข้อมูลที่ระบบจำเป็นต้องใช้ให้ครบตั้งแต่สมัคร
 * (ชื่อ-นามสกุล เบอร์โทร เลขบัตรประชาชน และที่อยู่) เดิมรับแค่ username/email/password
 * แล้วไปไล่ขอทีหลังเป็นจุด ๆ — ที่อยู่ตอนจะยืนยันคำสั่งซื้อ ชื่อกับเลขบัตรตอนจะทำสัญญา
 * ลิขสิทธิ์ ซึ่งทำให้ผู้ซื้อสะดุดกลางทางทุกครั้งที่จะทำอะไรให้จบสักอย่าง
 *
 * กฎการตรวจของแต่ละ field ยกมาจาก RegisterSellerRequest ทั้งชุด
 * ข้อมูลคนละชุดกฎระหว่างผู้ซื้อกับผู้ขายจะกลายเป็นบั๊กทันทีที่ผู้ซื้อสมัครเป็นผู้ขายต่อ
 */
@Data
public class RegisterBuyerRequest {

    /**
     * Username — เดิม SRS กำหนดให้เป็นภาษาอังกฤษหรือตัวเลขเท่านั้น
     * ตอนนี้เปิดรับอักษรไทยและ _ . - ด้วย ให้ตรงกับหน้าแก้ไขโปรไฟล์
     * (ถ้าสมัครกับแก้ไขใช้กฎคนละชุด ผู้ใช้จะตั้งชื่อตอนสมัครไม่ได้
     *  แต่ไปเปลี่ยนเป็นชื่อเดียวกันนั้นได้ทีหลัง ซึ่งไม่สมเหตุสมผล)
     *
     * ความยาวขยายจาก 8-20 เป็น 8-50 เพราะชื่อไทยนับสระและวรรณยุกต์เป็นตัวอักษรด้วย
     * เพดาน 20 จึงแคบเกินไปสำหรับชื่อภาษาไทย
     *
     * กฎที่เหลือคงเดิม: ไม่มีเว้นวรรค ไม่เป็นค่าว่าง
     *
     * ⚠️ ต้องตรงกับ validateUsername() ใน frontend/src/lib/validation.ts
     */
    @NotBlank(message = "กรุณากรอกชื่อผู้ใช้")
    @Pattern(regexp = "^[a-zA-Z0-9_.\\-\\u0E00-\\u0E7F]{8,50}$",
             message = "ชื่อผู้ใช้ใช้ได้เฉพาะตัวอักษรไทย/อังกฤษ ตัวเลข และ _ . - "
                     + "ความยาว 8-50 ตัวอักษร ไม่มีช่องว่าง")
    private String username;

    /**
     * Email — SRS กำหนด:
     * 1. ตัวอักษร a-z, A-Z หรือตัวเลข 0-9 (ก่อน @)
     * 2. ยาว 8-20 ตัวอักษร (รวม @domain)
     * 3-4. ไม่มีช่องว่าง, ไม่ว่าง
     * หมายเหตุ: ใช้ @Email เพิ่มเติมเพื่อตรวจรูปแบบ email มาตรฐาน
     */
    @NotBlank(message = "กรุณากรอกอีเมล")
    @Email(message = "รูปแบบอีเมลไม่ถูกต้อง")
    @Size(min = 8, max = 50, message = "อีเมลต้องมีความยาว 8-50 ตัวอักษร")
    private String email;

    /**
     * Password — SRS กำหนด:
     * 1. ตัวอักษรภาษาอังกฤษ, ตัวเลข หรืออักขระพิเศษ [ !#_. ]
     * 2. ยาว 8-16 ตัวอักษร
     * 3-4. ไม่มีช่องว่าง, ไม่ว่าง
     */
    @NotBlank(message = "กรุณากรอกรหัสผ่าน")
    @Pattern(regexp = "^[a-zA-Z0-9!#_.]{8,16}$",
             message = "รหัสผ่านต้องยาว 8-16 ตัวอักษร ใช้ได้เฉพาะ a-z A-Z 0-9 และ ! # _ .")
    private String password;

    /**
     * ชื่อ-นามสกุลจริง — ใช้เป็นชื่อผู้รับบนคำสั่งซื้อและชื่อผู้รับโอนบนสัญญาลิขสิทธิ์
     * จึงต้องตรงกับบัตรประชาชน กฎเดียวกับ RegisterSellerRequest.fullName
     *
     * ⚠️ ต้องตรงกับ validateFullName() ใน frontend/src/lib/validation.ts
     */
    @NotBlank(message = "กรุณากรอกชื่อ-นามสกุล")
    @Pattern(regexp = "^[a-zA-Z\\u0E00-\\u0E7F][a-zA-Z\\u0E00-\\u0E7F.'\\-]*\\s+"
                    + "[a-zA-Z\\u0E00-\\u0E7F][a-zA-Z\\u0E00-\\u0E7F.'\\s\\-]*$",
             message = "ชื่อ-นามสกุลต้องเป็นภาษาไทยหรือภาษาอังกฤษ "
                     + "และมีช่องว่างคั่นระหว่างชื่อกับนามสกุล")
    private String fullName;

    /** เบอร์โทรศัพท์ — ผู้ขายและขนส่งใช้ติดต่อตอนส่งของ */
    @NotBlank(message = "กรุณากรอกเบอร์โทรศัพท์")
    @Pattern(regexp = "^[0-9]{10}$",
             message = "เบอร์โทรศัพท์ต้องเป็นตัวเลข 10 หลัก ไม่มีช่องว่าง")
    private String phoneNumber;

    /**
     * เลขบัตรประชาชน 13 หลัก — เป็นคู่สัญญาในสัญญาโอนลิขสิทธิ์ และเป็นเลขประจำตัว
     * ผู้เสียภาษีบนใบเสนอราคา ขอตั้งแต่สมัครเพื่อไม่ต้องไปสะดุดตอนจะทำสัญญา
     */
    @NotBlank(message = "กรุณากรอกเลขบัตรประชาชน")
    @Pattern(regexp = "^[0-9]{13}$", message = "เลขบัตรประชาชนต้องเป็นตัวเลข 13 หลัก")
    private String nationalNo;

    /**
     * ที่อยู่รายการแรกในสมุดที่อยู่ — ใช้เป็นที่อยู่จัดส่งตั้งต้น
     * ผู้ซื้อเพิ่มที่อยู่อื่นทีหลังได้ และเลือกได้ตอนสั่งซื้อ
     *
     * ใช้ชนิดเดียวกับของผู้ขายโดยตั้งใจ จะได้ไม่มีกฎที่อยู่สองชุดที่หลุดจากกันเวลาแก้
     */
    @Valid
    @NotNull(message = "กรุณากรอกข้อมูลที่อยู่")
    private RegisterSellerRequest.AddressRequest address;
}
