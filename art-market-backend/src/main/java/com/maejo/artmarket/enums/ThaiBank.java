package com.maejo.artmarket.enums;

/**
 * ธนาคารที่ผู้ขายเลือกเป็นบัญชีรับเงินได้
 *
 * ใช้ enum แทนให้พิมพ์ชื่อธนาคารเอง — ชื่อที่พิมพ์เองสะกดได้หลายแบบ
 * ("กสิกร", "KBank", "ธ.กสิกรไทย") แอดมินต้องมาเดาเองตอนโอน และตรวจความถูกต้องไม่ได้
 * รหัสย่อตรงกับที่ธนาคารใช้กันทั่วไป ส่วนชื่อไทยใช้แสดงผล
 *
 * ⚠️ ต้องตรงกับ THAI_BANKS ใน frontend/src/lib/banks.ts
 */
public enum ThaiBank {
    KBANK("ธนาคารกสิกรไทย"),
    SCB("ธนาคารไทยพาณิชย์"),
    BBL("ธนาคารกรุงเทพ"),
    KTB("ธนาคารกรุงไทย"),
    BAY("ธนาคารกรุงศรีอยุธยา"),
    TTB("ธนาคารทหารไทยธนชาต"),
    GSB("ธนาคารออมสิน"),
    BAAC("ธนาคารเพื่อการเกษตรและสหกรณ์การเกษตร (ธ.ก.ส.)"),
    GHB("ธนาคารอาคารสงเคราะห์"),
    UOB("ธนาคารยูโอบี"),
    CIMB("ธนาคารซีไอเอ็มบี ไทย"),
    KKP("ธนาคารเกียรตินาคินภัทร"),
    LHB("ธนาคารแลนด์ แอนด์ เฮ้าส์"),
    TISCO("ธนาคารทิสโก้"),
    ISBT("ธนาคารอิสลามแห่งประเทศไทย");

    private final String displayName;

    ThaiBank(String displayName) {
        this.displayName = displayName;
    }

    public String getDisplayName() {
        return displayName;
    }
}
