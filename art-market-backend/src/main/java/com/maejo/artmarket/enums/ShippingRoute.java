package com.maejo.artmarket.enums;

/**
 * เส้นทางจัดส่ง คำนวณจากจังหวัดต้นทาง (ที่อยู่ผู้ขาย) เทียบกับจังหวัดปลายทาง (ที่อยู่ผู้ซื้อ)
 * อ้างอิงการแบ่งเส้นทางในตารางราคาของ Flash Express ซึ่งคิดราคาต่างกันตามเส้นทาง
 *
 * ขนส่งที่คิดเรทเดียวทั้งประเทศ (Kerry, ไปรษณีย์ไทย) จะไม่สนใจค่านี้
 */
public enum ShippingRoute {

    /** ต้นทางและปลายทางอยู่จังหวัดเดียวกัน — ถูกที่สุด */
    SAME_PROVINCE,

    /** ทั้งต้นทางและปลายทางอยู่ในกรุงเทพฯ และปริมณฑล */
    WITHIN_METRO,

    /** ต้นทางอยู่ กทม./ปริมณฑล ปลายทางเป็นต่างจังหวัด */
    METRO_TO_PROVINCE,

    /** ต้นทางเป็นต่างจังหวัด ปลายทางอยู่ กทม./ปริมณฑล */
    PROVINCE_TO_METRO,

    /** ต่างจังหวัดไปต่างจังหวัด คนละจังหวัดกัน */
    CROSS_PROVINCE
}
