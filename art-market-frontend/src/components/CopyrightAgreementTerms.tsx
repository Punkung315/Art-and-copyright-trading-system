const TERMS_BY_VERSION: Record<string, Clause[]> = {
  "v1-2026": TERMS_V1,
};

/**
 * เลือกข้อความตามเวอร์ชันที่บันทึกไว้ในสัญญา ไม่ใช่เวอร์ชันล่าสุดเสมอ
 *
 * สัญญาเก่าที่ไม่มี termsVersion (สร้างก่อนมีคอลัมน์นี้) ใช้ v1-2026 ไปก่อน
 * ซึ่งเป็นเวอร์ชันแรกอยู่แล้ว จึงไม่ทำให้เนื้อหาเปลี่ยนไปจากที่เคยเห็น
 */
export function termsFor(version?: string): Clause[] {
  return TERMS_BY_VERSION[version ?? CURRENT_TERMS_VERSION] ?? TERMS_V1;
}

export function CopyrightAgreementTerms({ transfer }: { transfer: CopyrightTransfer }) {
  return (
    <>
      {termsFor(transfer.termsVersion).map((clause) => (
        <section key={clause.heading} className="break-inside-avoid">
          <h2 className="mt-5 text-sm font-bold text-stone-900">{clause.heading}</h2>
          {clause.body.map((paragraph, i) => (
            <p key={i} className="mt-1.5 text-justify indent-8 text-sm leading-relaxed text-stone-700">
              {paragraph}
            </p>
          ))}
        </section>
      ))}
    </>
  );
}
