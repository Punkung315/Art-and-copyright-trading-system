/**
 * ตัดช่องว่างหน้า-หลัง และยุบช่องว่างซ้ำกลางข้อความ
 *
 * ค่าพวกนี้ถูกนำไปสร้างตัวกรองในหน้าค้นหาโดยตรง ("ผ้าใบ" กับ "ผ้าใบ " จะกลายเป็นสองตัวเลือก
 * ทั้งที่ผู้ใช้ตั้งใจพิมพ์ค่าเดียวกัน) จึงต้องล้างให้เรียบร้อยก่อนส่งไป backend
 */
export function normalizeOption(value: string): string {
  return value.trim().replace(/\s+/g, " ");
}

/** รวมรายการแนะนำกับค่าที่มีอยู่จริง โดยไม่ให้ซ้ำและคงลำดับรายการตั้งต้นไว้ก่อน */
export function mergeOptions(base: readonly string[], fromData: string[] = []): string[] {
  const seen = new Set<string>();
  const out: string[] = [];
  for (const v of [...base, ...fromData]) {
    const k = normalizeOption(v);
    if (!k || seen.has(k)) continue;
    seen.add(k);
    out.push(k);
  }
  return out;
}
